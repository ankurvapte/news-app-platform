#!/usr/bin/env sh
# Creates a trusted local HTTPS certificate for the gateway with mkcert.
# Writes certs/local.pem, certs/local-key.pem and certs/tls.yml (Traefik dynamic
# config pointing at them). certs/ is git-ignored and mounted read-only into the
# gateway, which picks the files up without a restart. With certs/ empty or
# missing, Traefik serves its self-signed default certificate instead.
#
# One-time setup: install mkcert, then run `mkcert -install` (asks for your
# password; adds mkcert's local CA to the macOS trust store).
set -eu
cd "$(dirname "$0")/.."
command -v mkcert >/dev/null || { echo "mkcert not found; see README 'Trusted local HTTPS'" >&2; exit 1; }

host="${PUBLIC_HOST:-localhost}"
mkdir -p certs
mkcert -cert-file certs/local.pem -key-file certs/local-key.pem "$host" localhost 127.0.0.1 ::1

cat > certs/tls.yml <<'YAML'
# Generated by scripts/make-local-cert.sh. Traefik dynamic config (file provider).
tls:
  stores:
    default:
      defaultCertificate:
        certFile: /certs/local.pem
        keyFile: /certs/local-key.pem
YAML
echo "Wrote certs/. The gateway reloads it automatically."
